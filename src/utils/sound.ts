  // Complete game win fanfare
  public playVictory() {
    if (this.isMuted) return;
    try {
      this.initContext();
      if (!this.ctx) return;

      const chord1 = [523.25, 659.25, 783.99]; // C major
      const chord2 = [587.33, 739.99, 880.00]; // D major
      const chord3 = [659.25, 830.61, 987.77]; // E major
      const chord4 = [1046.5, 1318.5, 1567.98]; // C high

      const sequence = [
        { chords: chord1, time: 0, dur: 0.2 },
        { chords: chord2, time: 0.22, dur: 0.2 },
        { chords: chord3, time: 0.44, dur: 0.3 },
        { chords: chord4, time: 0.78, dur: 0.8 },
      ];

      sequence.forEach((seq) => {
        seq.chords.forEach((freq) => {
          if (!this.ctx) return;
          const osc = this.ctx.createOscillator();
          const gain = this.ctx.createGain();

          osc.type = 'triangle';
          osc.frequency.setValueAtTime(freq, this.ctx.currentTime + seq.time);

          gain.gain.setValueAtTime(0.2, this.ctx.currentTime + seq.time);
          gain.gain.exponentialRampToValueAtTime(0.001, this.ctx.currentTime + seq.time + seq.dur);

          osc.connect(gain);
          gain.connect(this.ctx.destination);

          osc.start(this.ctx.currentTime + seq.time);
          osc.stop(this.ctx.currentTime + seq.time + seq.dur);
        });
      });
    } catch {
      // ignore
    }
  }

